public class Numeros{
	public static void main(String[] args){
		int numero = 10; // Iniciamos contador a 10
		while (numero > 0){ // Ponemos una condicion para cuando el numero sea menor que 0 no entre al bucle.
			System.out.println("numero: " +numero); // que te imprima los numeros de manera regresiva por eso el menos
			numero--; //Y restamos el numero es decir, numero = numero - 1. restamos 1 al numero que sale del bucle hasta que la condición deje de cumplirse 
		}
	}

}
	